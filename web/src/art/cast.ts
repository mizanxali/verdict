const STYLES: HairStyle[] = ["crop", "wavy", "sidePart", "ponytail", "curly", "bob", "slick"];
const OUTFITS: Outfit[] = ["suit", "cardigan", "sweater", "tweed", "zip"];
const CLOTH = ["#3d5a80", "#7a4b6b", "#4f7a54", "#8a5a2b", "#5b5f73", "#9c3f3a", "#2f6f73"];

/** Deterministic fallback so an unknown case still gets a full, varied cast. */
export function designFor(id: string): Design {
  const known = DESIGNS[id];
  if (known) return known;
  let h = 7;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0;
  const pick = <T,>(arr: T[], salt: number) => arr[(h >>> salt) % arr.length]!;
  return {
    skin: pick(SKIN, 1),
    hair: pick(HAIR, 4),
    hairStyle: pick(STYLES, 7),
    outfit: pick(OUTFITS, 10),
    top: pick(CLOTH, 13),
    under: "#f1ebe0",
    accent: pick(CLOTH, 16),
    bottom: "#33303a",
    shoes: "#1c181e",
    build: 0.92 + ((h >>> 19) % 30) / 100,
    height: 0.96 + ((h >>> 22) % 9) / 100,
    skirt: ((h >>> 25) & 1) === 1,
    acc: ((h >>> 27) & 1) === 1 ? ["glassesRect"] : [],
  };
}
